import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from '@playwright/test';

const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'no-preference', timezoneId: 'America/Montevideo' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await mkdir('docs/trailer/captures', { recursive: true });
await page.goto('http://127.0.0.1:5173');
await page.locator('[data-cinematic-intro]').waitFor();
const openedAt = Date.now();
assert.equal(await page.locator('[data-cinematic-intro] button').count(), 0);
assert.equal(await page.evaluate(() => document.getElementById('root').inert), true);
assert.equal(await page.locator('.cosmos-orbiter-primary').first().evaluate(el => getComputedStyle(el).animationPlayState), 'paused');
await page.keyboard.press('Tab');
assert.equal(await page.evaluate(() => document.activeElement.hasAttribute('data-cinematic-intro')), true);
await page.waitForTimeout(1550);
await page.screenshot({ path: 'docs/trailer/captures/intro-convergence-desktop.png' });
await page.locator('[data-cinematic-intro]').waitFor({ state: 'detached', timeout: 4200 });
const duration = Date.now() - openedAt;
assert.ok(duration <= 4200, `Intro ended after ${duration} ms`);
assert.equal(await page.evaluate(() => document.getElementById('root').inert), false);
assert.equal(await page.evaluate(() => document.activeElement.id), 'main-content');
await page.reload();
await page.locator('[data-cinematic-intro]').waitFor();
await page.keyboard.press('Escape');
await page.locator('[data-cinematic-intro]').waitFor({ state: 'detached' });
await page.waitForTimeout(700);
await page.locator('.cosmic-installation[data-active="true"]').waitFor();
const firstOrbit = await page.locator('.cosmos-orbiter-primary').first().evaluate(el => getComputedStyle(el).transform);
await page.waitForTimeout(700);
const nextOrbit = await page.locator('.cosmos-orbiter-primary').first().evaluate(el => getComputedStyle(el).transform);
assert.notEqual(firstOrbit, nextOrbit);
await page.screenshot({ path: 'docs/trailer/captures/hero-motion-desktop.png' });
await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight));
await page.locator('.cosmic-installation[data-active="false"]').waitFor();
assert.equal(await page.locator('.cosmos-orbiter-primary').first().evaluate(el => getComputedStyle(el).animationPlayState), 'paused');
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.getByRole('button', { name: 'Volver a vivir el inicio' }).click();
await page.locator('[data-cinematic-intro]').waitFor({ state: 'detached' });
assert.equal(await page.evaluate(() => document.getElementById('root').inert), false);
assert.equal(await page.getByRole('button', { name: 'Volver a vivir el inicio' }).evaluate(el => el === document.activeElement), true);
await page.setViewportSize({ width: 390, height: 844 });
await page.emulateMedia({ reducedMotion: 'no-preference' });
await page.getByRole('button', { name: 'Volver a vivir el inicio' }).click();
await page.locator('[data-cinematic-intro]').waitFor();
await page.waitForTimeout(1650);
await page.screenshot({ path: 'docs/trailer/captures/intro-convergence-mobile.png' });
await page.keyboard.press('Escape');
assert.deepEqual(errors, []);
console.log(JSON.stringify({ introDurationMs: duration, refresh: true, noSkip: true, nativeFocus: true, orbitMoving: true, offscreenPaused: true, reducedFocusRestored: true, pageErrors: errors }));
await browser.close();
